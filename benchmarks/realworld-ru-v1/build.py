def issue(original, replacements, category, severity, why):
    return {
        "original": original,
        "replacements": replacements if isinstance(replacements, list) else [replacements],
        "category": category,
        "severity": severity,
        "why": why,
    }


ITEMS = []


def add(id_, category, text, expected, forbidden=None):
    ITEMS.append({
        "id": id_,
        "category": category,
        "text": text,
        "expected": expected,
        "forbidden": forbidden or [],
    })


