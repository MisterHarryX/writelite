"""Builds benchmarks/realworld-ru-v1/paragraphs.jsonl.

Paragraph-level release diagnostic set with manually written gold labels (Phase 7.5 §34–§36).
Written as a script because the content is Russian and the shell here mangles UTF-8.

Scoring conventions this file relies on:
  * `original` must appear verbatim in `text`; the harness locates it by substring.
  * `replacements` is a list of accepted results — applying the finding must yield a text
    CONTAINING one of them. Non-unique on purpose for style (§35).
  * `forbidden` lists rewrites that fail the release if produced (§38).
"""
