def main():
    os.makedirs(ROOT, exist_ok=True)
    path = os.path.join(ROOT, "paragraphs.jsonl")
    with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
        for item in ITEMS:
            handle.write(json.dumps(item, ensure_ascii=False) + "\n")

    # Every gold span must literally occur in its text, or the harness silently drops it.
    bad = 0
    for item in ITEMS:
        for e in item["expected"]:
            if e["original"] not in item["text"]:
                print(f"  BAD SPAN {item['id']}: «{e['original']}»")
                bad += 1

    total_expected = sum(len(i["expected"]) for i in ITEMS)
    by_cat = {}
    for i in ITEMS:
        for e in i["expected"]:
            by_cat[e["category"]] = by_cat.get(e["category"], 0) + 1

    print(f"{path}")
    print(f"  paragraphs      : {len(ITEMS)}")
    print(f"  expected issues : {total_expected}")
    print(f"  by category     : {by_cat}")
    print(f"  forbidden rules : {sum(len(i['forbidden']) for i in ITEMS)}")
    print(f"  bad spans       : {bad}")


if __name__ == "__main__":
    main()
